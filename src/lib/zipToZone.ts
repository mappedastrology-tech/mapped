/**
 * Look up USDA Hardiness Zone from a US zip code.
 * Returns the zone string (e.g. "8b") or null if not found.
 */
export function getZoneFromZip(zip: string): string | null {
  // Clean input: digits only
  const digits = zip.replace(/\D/g, "");
  if (digits.length < 3) return null;
  const prefix = digits.slice(0, 3);
  return ZIP3_TO_ZONE[prefix] || null;
}

/**
 * Validate that a string looks like a US zip code (5 digits, optionally +4).
 */
export function isValidZip(zip: string): boolean {
  return /^\d{5}(-\d{4})?$/.test(zip.trim());
}
