"""
Generate src/lib/astro/chironTable.ts — Chiron's geocentric longitude table.

Chiron has no analytic theory a browser can run cheaply, and a Keplerian
model drifts by degrees (Saturn and Uranus perturb it hard). So the app reads
a precomputed table instead and interpolates it (see chironEphemeris.ts).

Source: Swiss Ephemeris (pyswisseph) with the seas_18.se1 asteroid file,
which covers 1800-2399; the table spans 1801-2200. Values are apparent
geocentric tropical longitude of date (Swiss defaults: light-time,
aberration, nutation) at 0h UT, the same frame astronomy-engine gives the
app for the other planets.

Run:
  python3 -m venv .venv && .venv/bin/pip install pyswisseph
  # download seas_18.se1 (and sepl_18.se1) from
  # https://github.com/aloistr/swisseph/tree/master/ephe into EPHE_DIR
  .venv/bin/python scripts/generate_chiron_table.py EPHE_DIR > src/lib/astro/chironTable.ts

Encoding: the longitude is unwrapped (allowed past 360) and quantized to
0.0001 deg. The first value is stored as a number; each later value is the
difference from the one before, offset by 2^17 and written as three base64
digits (18 bits). Quantizing the running value, not each difference, means
the decoded table never drifts.
"""

import math
import sys
import swisseph as swe

START_YEAR = 1801  # seas_18 starts 1800-01-01 exactly; leave a margin
END_YEAR = 2200
STEP_DAYS = 10
SCALE = 10000  # units per degree
OFFSET = 1 << 17
B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"


def main() -> None:
    swe.set_ephe_path(sys.argv[1])
    start = swe.julday(START_YEAR, 1, 1, 0.0)
    end = swe.julday(END_YEAR, 1, 1, 0.0)
    n = math.ceil((end - start) / STEP_DAYS) + 1  # last row on or after END_YEAR-01-01

    units = []
    prev = None
    for i in range(n):
        jd = start + i * STEP_DAYS
        (lon, *_rest), flags = swe.calc_ut(jd, swe.CHIRON, swe.FLG_SWIEPH)
        if not flags & swe.FLG_SWIEPH:
            raise SystemExit(f"Swiss Ephemeris file missing at JD {jd} (flags {flags})")
        if prev is not None:
            while lon - prev > 180:
                lon -= 360
            while lon - prev < -180:
                lon += 360
        prev = lon
        units.append(round(lon * SCALE))

    out = []
    for a, b in zip(units, units[1:]):
        v = b - a + OFFSET
        if not 0 <= v < (1 << 18):
            raise SystemExit("difference out of range")
        out.append(B64[v >> 12] + B64[(v >> 6) & 63] + B64[v & 63])
    body = "".join(out)
    lines = [body[i:i + 120] for i in range(0, len(body), 120)]

    print("// GENERATED by scripts/generate_chiron_table.py — do not edit by hand.")
    print(f"// Swiss Ephemeris {swe.version}, seas_18.se1. Chiron, apparent geocentric")
    print(f"// tropical longitude of date, 0h UT every {STEP_DAYS} days, {START_YEAR}-01-01 to {END_YEAR}-01-01.")
    print("// Encoding is described in the generator.")
    print()
    print(f"export const CHIRON_START_JD = {start};")
    print(f"export const CHIRON_STEP_DAYS = {STEP_DAYS};")
    print(f"export const CHIRON_COUNT = {n};")
    print(f"export const CHIRON_SCALE = {SCALE};")
    print(f"export const CHIRON_FIRST = {units[0]};")
    print("export const CHIRON_DELTAS =")
    print(" +\n".join(f'  "{line}"' for line in lines) + ";")


if __name__ == "__main__":
    main()
