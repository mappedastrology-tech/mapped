#!/usr/bin/env node
/**
 * Regenerates src/lib/astro/tzBackzone.ts — pre-1970 offset history that the
 * JS runtime's own time-zone data (ICU) does not carry.
 *
 * ICU is built from the IANA "main" data. Since 2022 that data merges zones
 * that agree after 1970 (Europe/Amsterdam → Brussels, Atlantic/Reykjavik →
 * Abidjan, Europe/Oslo → Berlin …) and moves their real earlier history to
 * the separate `backzone` file, which ICU leaves out. So Intl tells us Iceland
 * was on GMT in 1965 (it was UTC−1) and Amsterdam on Brussels time in 1935 (it
 * was Amsterdam Mean Time, +0:19:32). For birth charts that is a wrong chart.
 *
 * This script compiles the full IANA source including backzone with the
 * system `zic`, reads every backzone zone's transitions up to 1970 with
 * `zdump`, and keeps only zones whose history differs from what this Node's
 * Intl reports. Run it when the IANA data or the Node/ICU version moves:
 *
 *   curl -sSfLO https://data.iana.org/time-zones/tzdata-latest.tar.gz
 *   mkdir tzsrc && tar xzf tzdata-latest.tar.gz -C tzsrc
 *   node scripts/gen-tz-backzone.mjs tzsrc
 */

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/gen-tz-backzone.mjs <unpacked tzdata dir>");
  process.exit(1);
}

const version = readFileSync(join(src, "version"), "utf8").trim();
const out = mkdtempSync(join(tmpdir(), "tzbz-"));
const files = ["africa", "antarctica", "asia", "australasia", "europe", "northamerica", "southamerica", "etcetera", "backzone"];
execFileSync("zic", ["-b", "fat", "-d", out, ...files.map((f) => join(src, f))]);

const zones = readFileSync(join(src, "backzone"), "utf8")
  .split("\n")
  .filter((l) => l.startsWith("Zone"))
  .map((l) => l.split(/\s+/)[1]);

const MONTHS = { Jan: 0, Feb: 1, Mar: 2, Apr: 3, May: 4, Jun: 5, Jul: 6, Aug: 7, Sep: 8, Oct: 9, Nov: 10, Dec: 11 };
const CUTOFF = Date.UTC(1970, 0, 1) / 1000;

/** zdump lines → [{ t: utcSeconds, off: seconds, dst, abbr }] for each state. */
function states(zone) {
  const txt = execFileSync("zdump", ["-v", "-c", "1800,1970", join(out, zone)], { encoding: "utf8" });
  const rows = [];
  for (const line of txt.split("\n")) {
    const m = line.match(/ (\w{3}) (\w{3}) +(\d+) (\d\d):(\d\d):(\d\d) (\d{4}) UT = .* (\S+) isdst=(\d) gmtoff=(-?\d+)$/);
    if (!m) continue;
    const t = Date.UTC(+m[7], MONTHS[m[2]], +m[3], +m[4], +m[5], +m[6]) / 1000;
    rows.push({ t, abbr: m[8], dst: +m[9], off: +m[10] });
  }
  return rows;
}

function intlOffset(zone, utcSeconds) {
  try {
    const s = new Intl.DateTimeFormat("en-US", { timeZone: zone, timeZoneName: "longOffset" })
      .formatToParts(new Date(utcSeconds * 1000)).find((p) => p.type === "timeZoneName").value;
    const m = s.match(/GMT([+-])(\d\d):(\d\d)(?::(\d\d))?/);
    if (!m) return 0;
    return (m[1] === "-" ? -1 : 1) * (+m[2] * 3600 + +m[3] * 60 + +(m[4] || 0));
  } catch {
    return null;
  }
}

const table = {};
for (const zone of zones) {
  // CET, MET and the like are not places anyone is born in.
  if (!zone.includes("/")) continue;
  const rows = states(zone);
  if (!rows.length) continue;
  // Collapse zdump's before/after pairs into the initial state + transitions.
  const initial = rows[0];
  const transitions = [];
  let prev = initial;
  for (const r of rows.slice(1)) {
    if (r.off !== prev.off || r.dst !== prev.dst || r.abbr !== prev.abbr) {
      if (r.t < CUTOFF) transitions.push([r.t, r.off, r.dst]);
      prev = r;
    }
  }
  // Keep the zone only if Intl disagrees somewhere before 1970.
  const samples = [transitions.length ? transitions[0][0] - 86400 : CUTOFF - 86400, ...transitions.map((t) => t[0] + 3600)];
  const differs = samples.some((t, i) => intlOffset(zone, t) !== (i === 0 ? initial.off : transitions[i - 1][1]));
  if (!differs) continue;
  table[zone] = {
    lmt: initial.abbr === "LMT" ? initial.off : null,
    initial: initial.off,
    transitions,
  };
}

const lines = [];
lines.push("/**");
lines.push(" * GENERATED by scripts/gen-tz-backzone.mjs from IANA tzdata " + version + " (backzone).");
lines.push(" * Do not edit by hand — regenerate. See src/lib/astro/birthTimezone.ts for how it is used.");
lines.push(" *");
lines.push(" * Per zone: `initial` offset (seconds east of UTC) before the first transition,");
lines.push(" * `lmt` = that initial offset when it is the reference city's Local Mean Time,");
lines.push(" * and transitions [utcSeconds, offsetSeconds, isDst] up to 1970-01-01. After");
lines.push(" * 1970 the runtime's own data is correct for every zone listed here.");
lines.push(" */");
lines.push("");
lines.push("export interface BackzoneHistory {");
lines.push("  lmt: number | null;");
lines.push("  initial: number;");
lines.push("  transitions: [number, number, 0 | 1][];");
lines.push("}");
lines.push("");
lines.push(`export const BACKZONE_VERSION = "${version}";`);
lines.push("");
lines.push("export const BACKZONE: Record<string, BackzoneHistory> = {");
for (const [zone, h] of Object.entries(table)) {
  lines.push(`  "${zone}": { lmt: ${h.lmt}, initial: ${h.initial}, transitions: [${h.transitions.map((t) => `[${t.join(",")}]`).join(",")}] },`);
}
lines.push("};");
lines.push("");

writeFileSync(new URL("../src/lib/astro/tzBackzone.ts", import.meta.url), lines.join("\n"));
console.log(`tzdata ${version}: ${Object.keys(table).length} of ${zones.length} backzone zones differ from this runtime's Intl.`);
